function getAllSources(config: McuProjectConfig): { cFiles: string[]; cppFiles: string[] } {
  const cSet = new Set<string>();
  const cppSet = new Set<string>();
  const disabledSet = new Set((config.disabledFiles || []).map((f) => toPosixPath(f)));

  for (const grp of config.sourceGroups) {
    for (const f of grp.files) {
      const norm = toPosixPath(f);
      if (disabledSet.has(norm)) continue;
      if (/\.(cpp|cc|cxx)$/i.test(norm)) {
        cppSet.add(norm);
      } else {
        cSet.add(norm);
      }
    }
  }
  return {
    cFiles: Array.from(cSet),
    cppFiles: Array.from(cppSet),
  };
}

/** Resolve full C compiler path for clangd --query-driver and compile_commands.json */
export function resolveCompilerPath(config: McuProjectConfig, kind: 'c' | 'cxx' | 'gdb' = 'c'): string {
  const platform = getHostPlatform();
  const tc = config.toolchain;

  if (kind === 'c' && tc.ccExecutable.trim()) return toPosixPath(tc.ccExecutable.trim());
  if (kind === 'cxx' && tc.cxxExecutable.trim()) return toPosixPath(tc.cxxExecutable.trim());
  if (kind === 'gdb' && tc.gdbExecutable.trim()) return toPosixPath(tc.gdbExecutable.trim());

  const toolBase =
    kind === 'c' ? `${tc.prefix}gcc` : kind === 'cxx' ? `${tc.prefix}g++` : `${tc.prefix}gdb`;
  const toolExe = exeName(toolBase, platform);

  if (tc.compilerDir.trim()) {
    return `${withTrailingSlash(tc.compilerDir)}${toolExe}`;
  }
  return toolBase;
}

/** Generate cross-platform Makefile */
export function generateMakefile(config: McuProjectConfig): string {
  const { cFiles, cppFiles } = getAllSources(config);
  const isGenericC = config.projectKind === 'generic-c';
  const hasCpp = cppFiles.length > 0;
  const tc = config.toolchain;
  const fl = config.flags;
  const dbg = config.debugger;

  const gccPathLine = config.useLocalMk
    ? `GCC_PATH ?=`
    : tc.compilerDir.trim()
      ? `GCC_PATH ?= ${withTrailingSlash(tc.compilerDir)}`
      : `GCC_PATH ?=`;

  const ccExpr = tc.ccExecutable.trim() ? toPosixPath(tc.ccExecutable.trim()) : `$(PREFIX)gcc`;
  const cxxExpr = tc.cxxExecutable.trim() ? toPosixPath(tc.cxxExecutable.trim()) : `$(PREFIX)g++`;
  const asExpr = tc.asExecutable.trim() ? toPosixPath(tc.asExecutable.trim()) : `$(PREFIX)gcc -x assembler-with-cpp`;
  const cpExpr = tc.objcopyExecutable.trim() ? toPosixPath(tc.objcopyExecutable.trim()) : `$(PREFIX)objcopy`;
  const szExpr = tc.sizeExecutable.trim() ? toPosixPath(tc.sizeExecutable.trim()) : `$(PREFIX)size`;

  const libDirFlags = (config.libSearchDirs || [])
    .map((d) => `-L${toPosixPath(d)}`)
    .join(' ');
  const staticLibArgs = (config.staticLibs || [])
    .map((lib) => toPosixPath(lib))
    .join(' ');
  const combinedLibs = [libDirFlags, staticLibArgs, fl.libs].filter(Boolean).join(' ');
  const preBuildCmd = config.hooks?.preBuild?.trim() || '';
  const postBuildCmd = config.hooks?.postBuild?.trim() || '';

  const defsLine = config.defines.map((d) => `-D${d}`).join(' ');
  const includesBlock = config.includeDirs.length
    ? config.includeDirs.map((inc) => `  -I${toPosixPath(inc)}`).join(' \\\n')
    : '  -I.';

  const cSourcesBlock = cFiles.length
    ? cFiles.map((s) => `  ${s}`).join(' \\\n')
    : '';
  const cppSourcesBlock = cppFiles.length
    ? cppFiles.map((s) => `  ${s}`).join(' \\\n')
    : '';
  const asmSourcesBlock = config.asmSources.length
    ? config.asmSources.map((s) => `  ${s}`).join(' \\\n')
    : '';

  const targetOut = isGenericC
    ? `$(BUILD_DIR)/$(TARGET)$(EXE_EXT)`
    : `$(BUILD_DIR)/$(TARGET).elf`;

  const allTargets = [targetOut];
  if (!isGenericC && fl.generateHex) allTargets.push(`$(BUILD_DIR)/$(TARGET).hex`);
  if (!isGenericC && fl.generateBin) allTargets.push(`$(BUILD_DIR)/$(TARGET).bin`);

  const flashRecipe = buildFlashRecipe(config, targetOut);
  const debugRecipe = buildDebugServerRecipe(config);

  const lines: string[] = [
    `########################################################################`,
    `# Generated by MCU Forge Studio (${config.projectKind})`,
    `# Cross-platform GNU Makefile (Windows / macOS / Linux)`,
    `########################################################################`,
    ``,
    `TARGET := ${config.name}`,
    `BUILD_DIR := ${config.buildDir || 'build'}`,
    ``,
    `# Parallel compilation (override with JOBS=N or -jN)`,
    `JOBS ?= ${fl.parallelJobs || 8}`,
    `ifeq ($(filter -j% --jobs%,$(MAKEFLAGS)),)`,
    `MAKEFLAGS += -j$(JOBS)`,
    `endif`,
    ``,
    `# Toolchain`,
    ...(config.useLocalMk
      ? [`# Machine-specific paths (GCC_PATH, OPENOCD) are loaded from local.mk (git-ignored)`, `-include local.mk`]
      : []),
    gccPathLine,
    `PREFIX := $(GCC_PATH)${tc.prefix}`,
    `CC := ${ccExpr}`,
    ...(hasCpp ? [`CXX := ${cxxExpr}`] : []),
    `AS := ${asExpr}`,
    ...(!isGenericC ? [`CP := ${cpExpr}`, `SZ := ${szExpr}`, `NM := $(PREFIX)nm`, `OBJDUMP := $(PREFIX)objdump`] : []),
    ``,
    `ARM_INCLUDE ?= ${toPosixPath(tc.sysIncludeDir || '')}`,
    ``,
    `# Target & Flags`,
    `CPU := ${fl.cpuFlags}`,
    `C_DEFS := ${defsLine}`,
    `C_INCLUDES := \\`,
    `  $(if $(strip $(ARM_INCLUDE)),-isystem $(ARM_INCLUDE)) \\`,
    includesBlock,
    ``,
    `C_SOURCES :=${cSourcesBlock ? ' \\\n' + cSourcesBlock : ''}`,
    ...(hasCpp ? [``, `CPP_SOURCES :=${cppSourcesBlock ? ' \\\n' + cppSourcesBlock : ''}`] : []),
    `ASM_SOURCES :=${asmSourcesBlock ? ' \\\n' + asmSourcesBlock : ''}`,
    ``,
    `CFLAGS := $(CPU) $(C_DEFS) $(C_INCLUDES) \\`,
    `  -std=${fl.cStandard || 'gnu11'} ${fl.optimization} ${fl.debugInfo} ${fl.warnings} ${fl.extraCFlags} -MMD -MP`,
    `CFLAGS += $(EXTRA_CFLAGS)`,
    ...(hasCpp
      ? [
          `CXXFLAGS := $(CPU) $(C_DEFS) $(C_INCLUDES) \\`,
          `  -std=${fl.cxxStandard || 'gnu++17'} ${fl.optimization} ${fl.debugInfo} ${fl.warnings} ${fl.extraCFlags} -MMD -MP`,
          `CXXFLAGS += $(EXTRA_CXXFLAGS)`,
        ]
      : []),
    `ASFLAGS := $(CPU) $(C_DEFS) $(C_INCLUDES) ${fl.debugInfo} ${fl.extraAsFlags}`,
    ``,
  ];

  if (config.linkerScript.trim()) {
    lines.push(`LDSCRIPT := ${toPosixPath(config.linkerScript.trim())}`);
    lines.push(
      `LDFLAGS := $(CPU) -T$(LDSCRIPT) -Wl,-Map=$(BUILD_DIR)/$(TARGET).map,--cref ${fl.extraLdFlags}`
    );
  } else {
    lines.push(`LDFLAGS := $(CPU) ${fl.extraLdFlags}`);
  }
  lines.push(`LIBS := ${combinedLibs}`);
  lines.push(``);

  // Debugger variables
  if (dbg.type === 'openocd') {
    lines.push(`OPENOCD ?= ${config.useLocalMk ? 'openocd' : toPosixPath(dbg.serverPath || 'openocd')}`);
    if (!config.useLocalMk && dbg.openocdScriptsDir.trim()) {
      lines.push(`OPENOCD_SCRIPTS ?= ${toPosixPath(dbg.openocdScriptsDir.trim())}`);
    } else if (config.useLocalMk) {
      lines.push(`OPENOCD_SCRIPTS ?=`);
    }
    lines.push(`OPENOCD_INTERFACE ?= ${dbg.openocdInterface || 'interface/stlink.cfg'}`);
    lines.push(`OPENOCD_TARGET ?= ${dbg.openocdTarget || 'target/stm32f1x.cfg'}`);
    lines.push(``);
  }

  lines.push(
    `C_OBJECTS := $(addprefix $(BUILD_DIR)/,$(C_SOURCES:.c=.o))`,
    ...(hasCpp
      ? [`CPP_OBJECTS := $(addprefix $(BUILD_DIR)/,$(patsubst %.cxx,%.o,$(patsubst %.cc,%.o,$(CPP_SOURCES:.cpp=.o))))`]
      : []),
    `ASM_OBJECTS := $(addprefix $(BUILD_DIR)/,$(patsubst %.S,%.o,$(ASM_SOURCES:.s=.o)))`,
    `OBJECTS := $(C_OBJECTS)${hasCpp ? ' $(CPP_OBJECTS)' : ''} $(ASM_OBJECTS)`,
    `DEPS := $(C_OBJECTS:.o=.d)${hasCpp ? ' $(CPP_OBJECTS:.o=.d)' : ''}`,
    ``,
    `# Cross-platform OS helpers (Windows CMD vs macOS/Linux POSIX)`,
    `ifeq ($(OS),Windows_NT)`,
    `EXE_EXT := .exe`,
    `define make_dir`,
    `\t@if not exist "$(subst /,\\,$(dir $@))" mkdir "$(subst /,\\,$(dir $@))"`,
    `endef`,
    `RM_BUILD = if exist "$(subst /,\\,$(BUILD_DIR))" rmdir /S /Q "$(subst /,\\,$(BUILD_DIR))"`,
    `else`,
    `EXE_EXT :=`,
    `define make_dir`,
    `\t@mkdir -p "$(dir $@)"`,
    `endef`,
    `RM_BUILD = rm -rf "$(BUILD_DIR)"`,
    `endif`,
    ``,
    `.PHONY: all clean size verify flash debug-server pre-build post-build`,
    `all: ${preBuildCmd ? 'pre-build ' : ''}${allTargets.join(' ')}${postBuildCmd ? ' post-build' : ''}`,
    ``,
    ...(preBuildCmd ? [`pre-build:`, `\t${preBuildCmd}`, ``] : []),
    ...(postBuildCmd ? [`post-build: ${allTargets.join(' ')}`, `\t${postBuildCmd}`, ``] : []),
    `$(BUILD_DIR)/%.o: %.c Makefile`,
    `\t$(make_dir)`,
    `\t$(CC) -c $(CFLAGS) -MF"$(@:.o=.d)" $< -o $@`,
    ``
  );

  if (hasCpp) {
    lines.push(
      `$(BUILD_DIR)/%.o: %.cpp Makefile`,
      `\t$(make_dir)`,
      `\t$(CXX) -c $(CXXFLAGS) -MF"$(@:.o=.d)" $< -o $@`,
      ``
    );
  }

  lines.push(
    `$(BUILD_DIR)/%.o: %.s Makefile`,
    `\t$(make_dir)`,
    `\t$(AS) -c $(ASFLAGS) $< -o $@`,
    ``,
    `$(BUILD_DIR)/%.o: %.S Makefile`,
    `\t$(make_dir)`,
    `\t$(AS) -c $(ASFLAGS) $< -o $@`,
    ``,
    `${targetOut}: $(OBJECTS) Makefile${config.linkerScript.trim() ? ' $(LDSCRIPT)' : ''}`,
    `\t$(make_dir)`,
    `\t${hasCpp ? '$(CXX)' : '$(CC)'} $(OBJECTS) $(LDFLAGS) $(LIBS) -o $@`,
    ...(!isGenericC ? [`\t$(SZ) $@`] : []),
    ``
  );

  if (!isGenericC && fl.generateHex) {
    lines.push(
      `$(BUILD_DIR)/$(TARGET).hex: $(BUILD_DIR)/$(TARGET).elf`,
      `\t$(CP) -O ihex $< $@`,
      ``
    );
  }
  if (!isGenericC && fl.generateBin) {
    lines.push(
      `$(BUILD_DIR)/$(TARGET).bin: $(BUILD_DIR)/$(TARGET).elf`,
      `\t$(CP) -O binary -S $< $@`,
      ``
    );
  }

  lines.push(
    `clean:`,
    `\t@$(RM_BUILD)`,
    ``
  );

  if (!isGenericC) {
    lines.push(
      `size: $(BUILD_DIR)/$(TARGET).elf`,
      `\t$(SZ) $<`,
      ``,
      `verify: all`,
      `\t$(OBJDUMP) -h $(BUILD_DIR)/$(TARGET).elf`,
      `\t$(NM) -n $(BUILD_DIR)/$(TARGET).elf > $(BUILD_DIR)/$(TARGET).symbols.txt`,
      ``
    );
  }

  lines.push(
    `flash: ${targetOut}`,
    flashRecipe,
    ``,
    `debug-server:`,
    debugRecipe,
    ``,
    `-include $(DEPS)`,
    ``
  );

  return lines.join('\n');
}

function buildFlashRecipe(config: McuProjectConfig, targetOut: string): string {
  const dbg = config.debugger;
  const flashOrigin = config.memoryLayout?.flashOrigin?.trim() || '0x08000000';
  if (dbg.type === 'openocd') {
    const scriptsFlag = dbg.openocdScriptsDir.trim() ? `-s "$(OPENOCD_SCRIPTS)" ` : '';
    return `\t"$(OPENOCD)" ${scriptsFlag}-f "$(OPENOCD_INTERFACE)" -f "$(OPENOCD_TARGET)" -c "program $(abspath $<) verify reset exit"`;
  }
  if (dbg.type === 'jlink') {
    const exe = toPosixPath(dbg.serverPath || 'JLinkExe');
    const dev = dbg.deviceName || 'STM32F103RE';
    return `\t"${exe}" -device ${dev} -if ${dbg.interfaceMode.toUpperCase()} -speed 4000 -autoconnect 1 -CommandFile flash.jlink`;
  }
  if (dbg.type === 'stlink') {
    const exe = toPosixPath(dbg.serverPath || 'st-flash');
    return `\t"${exe}" --reset write $(BUILD_DIR)/$(TARGET).bin ${flashOrigin}`;
  }
  if (dbg.type === 'pyocd') {
    const exe = toPosixPath(dbg.serverPath || 'pyocd');
    const dev = dbg.deviceName ? `-t ${dbg.deviceName} ` : '';
    return `\t"${exe}" flash ${dev}$(abspath $<)`;
  }
  if (dbg.type === 'custom' && dbg.customFlashCommand.trim()) {
    const cmd = dbg.customFlashCommand
      .replace(/\$\{ELF\}/g, `$(abspath ${targetOut})`)
      .replace(/\$\{HEX\}/g, `$(abspath $(BUILD_DIR)/$(TARGET).hex)`)
      .replace(/\$\{BIN\}/g, `$(abspath $(BUILD_DIR)/$(TARGET).bin)`)
      .replace(/\$\{FLASH_ORIGIN\}/g, flashOrigin)
      .replace(/\$\{TARGET\}/g, `$(TARGET)`);
    return `\t${cmd}`;
  }
  if (config.projectKind === 'generic-c') {
    return `\t./${targetOut}`;
  }
  return `\t@echo "No flasher configured. Configure a debugger/flasher in MCU Forge Studio."`;
}

function buildDebugServerRecipe(config: McuProjectConfig): string {
  const dbg = config.debugger;
  if (dbg.type === 'openocd') {
    const scriptsFlag = dbg.openocdScriptsDir.trim() ? `-s "$(OPENOCD_SCRIPTS)" ` : '';
    return `\t"$(OPENOCD)" ${scriptsFlag}-f "$(OPENOCD_INTERFACE)" -f "$(OPENOCD_TARGET)"`;
  }
  if (dbg.type === 'jlink') {
    const exe = toPosixPath(dbg.serverPath || 'JLinkGDBServer');
    const dev = dbg.deviceName || 'STM32F103RE';
    return `\t"${exe}" -device ${dev} -if ${dbg.interfaceMode.toUpperCase()} -speed 4000`;
  }
  if (dbg.type === 'pyocd') {
    const exe = toPosixPath(dbg.serverPath || 'pyocd');
    const dev = dbg.deviceName ? `-t ${dbg.deviceName}` : '';
    return `\t"${exe}" gdbserver ${dev}`;
  }
  return `\t@echo "No debug server configured."`;
}

/** Generate cross-platform CMakeLists.txt */
export function generateCMakeLists(config: McuProjectConfig): string {
  const { cFiles, cppFiles } = getAllSources(config);
  const isGenericC = config.projectKind === 'generic-c';
  const hasCpp = cppFiles.length > 0;
  const fl = config.flags;
  const langs = ['C', ...(hasCpp ? ['CXX'] : []), ...(config.asmSources.length ? ['ASM'] : [])].join(' ');
  const exeTarget = isGenericC ? config.name : `${config.name}.elf`;

  const allSrcs = [...cFiles, ...cppFiles, ...config.asmSources];

  const lines: string[] = [
    `cmake_minimum_required(VERSION 3.20)`,
    ``,
    `# Generated by MCU Forge Studio (${config.projectKind})`,
    `set(CMAKE_EXPORT_COMPILE_COMMANDS ON)`,
    ``,
    ...(!isGenericC ? [`set(CMAKE_SYSTEM_NAME Generic)`, `set(CMAKE_TRY_COMPILE_TARGET_TYPE STATIC_LIBRARY)`, ``] : []),
    `project(${config.name} LANGUAGES ${langs})`,
    ``,
    `set(CMAKE_C_STANDARD ${fl.cStandard.replace(/^gnu/, '').replace(/^c/, '') || '11'})`,
    `set(CMAKE_C_EXTENSIONS ON)`,
    ...(hasCpp ? [`set(CMAKE_CXX_STANDARD ${fl.cxxStandard.replace(/^gnu\+\+/, '').replace(/^c\+\+/, '') || '17'})`] : []),
    ``,
    `add_executable(${exeTarget}`,
    ...allSrcs.map((s) => `    ${s}`),
    `)`,
    ``,
    `target_include_directories(${exeTarget} PRIVATE`,
    ...(config.includeDirs.length ? config.includeDirs.map((inc) => `    ${toPosixPath(inc)}`) : [`    .`]),
    `)`,
    ``,
  ];

  if (config.defines.length > 0) {
    lines.push(
      `target_compile_definitions(${exeTarget} PRIVATE`,
      ...config.defines.map((d) => `    ${d}`),
      `)`,
      ``
    );
  }

  const compileOpts = [fl.cpuFlags, fl.optimization, fl.debugInfo, fl.warnings, fl.extraCFlags]
    .join(' ')
    .split(/\s+/)
    .filter(Boolean);

  if (compileOpts.length > 0) {
    lines.push(
      `target_compile_options(${exeTarget} PRIVATE`,
      ...compileOpts.map((o) => `    ${o}`),
      `)`,
      ``
    );
  }

  const linkOpts = [
    ...fl.cpuFlags.split(/\s+/).filter(Boolean),
    ...(config.linkerScript.trim() ? [`-T\${CMAKE_SOURCE_DIR}/${toPosixPath(config.linkerScript.trim())}`] : []),
    ...fl.extraLdFlags.split(/\s+/).filter(Boolean),
  ];

  if (linkOpts.length > 0) {
    lines.push(
      `target_link_options(${exeTarget} PRIVATE`,
      ...linkOpts.map((o) => `    ${o}`),
      `)`,
      ``
    );
  }

  if ((config.libSearchDirs || []).length > 0) {
    lines.push(
      `target_link_directories(${exeTarget} PRIVATE`,
      ...(config.libSearchDirs || []).map((d) => `    \${CMAKE_SOURCE_DIR}/${toPosixPath(d)}`),
      `)`,
      ``
    );
  }

  const cmakeLibs = [
    ...(config.staticLibs || []).map((l) => `\${CMAKE_SOURCE_DIR}/${toPosixPath(l)}`),
    ...(fl.libs.trim() ? [fl.libs.trim()] : []),
  ];
  if (cmakeLibs.length > 0) {
    lines.push(`target_link_libraries(${exeTarget} PRIVATE ${cmakeLibs.join(' ')})`, ``);
  }

  if (config.hooks?.preBuild?.trim()) {
    lines.push(
      `add_custom_command(TARGET ${exeTarget} PRE_BUILD`,
      `    COMMAND ${config.hooks.preBuild.trim()}`,
      `    WORKING_DIRECTORY \${CMAKE_SOURCE_DIR}`,
      `)`,
      ``
    );
  }

  if (!isGenericC) {
    const objcopy = config.toolchain.objcopyExecutable.trim() || `${config.toolchain.prefix}objcopy`;
    const sizeTool = config.toolchain.sizeExecutable.trim() || `${config.toolchain.prefix}size`;
    lines.push(
      `add_custom_command(TARGET ${exeTarget} POST_BUILD`,
      `    COMMAND ${sizeTool} $<TARGET_FILE:${exeTarget}>`,
      ...(fl.generateHex ? [`    COMMAND ${objcopy} -O ihex $<TARGET_FILE:${exeTarget}> ${config.name}.hex`] : []),
      ...(fl.generateBin ? [`    COMMAND ${objcopy} -O binary -S $<TARGET_FILE:${exeTarget}> ${config.name}.bin`] : []),
      ...(config.hooks?.postBuild?.trim() ? [`    COMMAND ${config.hooks.postBuild.trim()}`] : []),
      `)`,
      ``
    );
  } else if (config.hooks?.postBuild?.trim()) {
    lines.push(
      `add_custom_command(TARGET ${exeTarget} POST_BUILD`,
      `    COMMAND ${config.hooks.postBuild.trim()}`,
      `    WORKING_DIRECTORY \${CMAKE_SOURCE_DIR}`,
      `)`,
      ``
    );
  }

  return lines.join('\n');
}

/** Generate CMake toolchain file when using CMake + cross compiler */
export function generateCMakeToolchain(config: McuProjectConfig): string {
  const cc = resolveCompilerPath(config, 'c');
  const cxx = resolveCompilerPath(config, 'cxx');
  return [
    `# Generated by MCU Forge Studio`,
    `set(CMAKE_SYSTEM_NAME Generic)`,
    `set(CMAKE_TRY_COMPILE_TARGET_TYPE STATIC_LIBRARY)`,
    `set(CMAKE_C_COMPILER "${cc}")`,
    `set(CMAKE_CXX_COMPILER "${cxx}")`,
    `set(CMAKE_ASM_COMPILER "${cc}")`,
    `set(CMAKE_FIND_ROOT_PATH_MODE_PROGRAM NEVER)`,
    `set(CMAKE_FIND_ROOT_PATH_MODE_LIBRARY ONLY)`,
    `set(CMAKE_FIND_ROOT_PATH_MODE_INCLUDE ONLY)`,
    ``,
  ].join('\n');
}

/** Generate compile_commands.json directly from project model (instant clangd / Vim / VSCode IntelliSense) */
export function generateCompileCommands(config: McuProjectConfig): string {
  const { cFiles, cppFiles } = getAllSources(config);
  const cc = resolveCompilerPath(config, 'c');
  const cxx = resolveCompilerPath(config, 'cxx');
  const fl = config.flags;
  const dir = toPosixPath(config.projectDir);

  const commonDefs = config.defines.map((d) => `-D${d}`);
  const commonIncs = [
    ...(config.toolchain.sysIncludeDir.trim() ? [`-isystem`, toPosixPath(config.toolchain.sysIncludeDir.trim())] : []),
    ...config.includeDirs.map((inc) => `-I${toPosixPath(inc)}`),
  ];
  const cpuTokens = fl.cpuFlags.split(/\s+/).filter(Boolean);
  const extraTokens = [fl.optimization, fl.debugInfo, fl.warnings, ...fl.extraCFlags.split(/\s+/)]
    .filter(Boolean);

  const entries: Array<{ directory: string; file: string; arguments: string[]; output: string }> = [];

  for (const rel of cFiles) {
    entries.push({
      directory: dir,
      file: `${dir}/${rel}`,
      output: `${dir}/${config.buildDir}/${rel.replace(/\.c$/i, '.o')}`,
      arguments: [
        cc,
        '-c',
        ...cpuTokens,
        ...commonDefs,
        ...commonIncs,
        `-std=${fl.cStandard || 'gnu11'}`,
        ...extraTokens,
        rel,
        '-o',
        `${config.buildDir}/${rel.replace(/\.c$/i, '.o')}`,
      ],
    });
  }

  for (const rel of cppFiles) {
    entries.push({
      directory: dir,
      file: `${dir}/${rel}`,
      output: `${dir}/${config.buildDir}/${rel.replace(/\.(cpp|cc|cxx)$/i, '.o')}`,
      arguments: [
        cxx,
        '-c',
        ...cpuTokens,
        ...commonDefs,
        ...commonIncs,
        `-std=${fl.cxxStandard || 'gnu++17'}`,
        ...extraTokens,
        rel,
        '-o',
        `${config.buildDir}/${rel.replace(/\.(cpp|cc|cxx)$/i, '.o')}`,
      ],
    });
  }

  return JSON.stringify(entries, null, 2) + '\n';
}

/** Generate .clangd for seamless VSCode & Vim/Neovim LSP */
export function generateClangdConfig(config: McuProjectConfig): string {
  const extraAdd = config.ide.clangdExtraArgs.length > 0 ? config.ide.clangdExtraArgs : ['-ferror-limit=0'];
  const isCross = config.projectKind !== 'generic-c';
  const removeFlags = isCross
    ? ['-mthumb-interwork', '-fconserve-stack', '-fno-var-tracking-assignments', '-Wa,*']
    : [];

  const lines = [
    `# Generated by MCU Forge Studio — works with VSCode clangd & Vim/Neovim LSP`,
    `CompileFlags:`,
    `  CompilationDatabase: .`,
    `  Add: [${extraAdd.map((a) => `"${a}"`).join(', ')}]`,
    ...(removeFlags.length ? [`  Remove: [${removeFlags.map((r) => `"${r}"`).join(', ')}]`] : []),
    `Diagnostics:`,
    `  UnusedIncludes: None`,
    `Index:`,
    `  Background: Build`,
    ``,
  ];
  return lines.join('\n');
}

/** Generate .vscode/tasks.json */
export function generateVscodeTasks(config: McuProjectConfig): string {
  const makeCmd = config.toolchain.makeExecutable.trim() || 'make';
  const cmakeCmd = config.toolchain.cmakeExecutable.trim() || 'cmake';

  const tasks =
    config.buildSystem === 'makefile'
      ? [
          {
            label: 'MCU Forge: Build',
            type: 'shell',
            command: makeCmd,
            args: ['all'],
            group: { kind: 'build', isDefault: true },
            problemMatcher: ['$gcc'],
          },
          {
            label: 'MCU Forge: Clean',
            type: 'shell',
            command: makeCmd,
            args: ['clean'],
            problemMatcher: [],
          },
          {
            label: 'MCU Forge: Flash',
            type: 'shell',
            command: makeCmd,
            args: ['flash'],
            dependsOn: ['MCU Forge: Build'],
            problemMatcher: ['$gcc'],
          },
        ]
      : [
          {
            label: 'MCU Forge: CMake Configure',
            type: 'shell',
            command: cmakeCmd,
            args: [
              '-B',
              config.buildDir || 'build',
              ...(config.projectKind !== 'generic-c'
                ? ['-DCMAKE_TOOLCHAIN_FILE=cmake/mcu-toolchain.cmake']
                : []),
              '-DCMAKE_EXPORT_COMPILE_COMMANDS=ON',
            ],
            problemMatcher: [],
          },
          {
            label: 'MCU Forge: Build',
            type: 'shell',
            command: cmakeCmd,
            args: ['--build', config.buildDir || 'build', '-j'],
            dependsOn: ['MCU Forge: CMake Configure'],
            group: { kind: 'build', isDefault: true },
            problemMatcher: ['$gcc'],
          },
          {
            label: 'MCU Forge: Clean',
            type: 'shell',
            command: cmakeCmd,
            args: ['--build', config.buildDir || 'build', '--target', 'clean'],
            problemMatcher: [],
          },
        ];

  return JSON.stringify({ version: '2.0.0', tasks }, null, 2) + '\n';
}

/** Generate .vscode/launch.json */
export function generateVscodeLaunch(config: McuProjectConfig): string {
  const isGenericC = config.projectKind === 'generic-c';
  const dbg = config.debugger;
  const gdbPath = resolveCompilerPath(config, 'gdb');
  const buildDir = config.buildDir || 'build';
  const elfPath =
    config.buildSystem === 'cmake'
      ? `\${workspaceFolder}/${buildDir}/${config.name}${isGenericC ? '' : '.elf'}`
      : `\${workspaceFolder}/${buildDir}/${config.name}${isGenericC ? '' : '.elf'}`;

  const configurations: Array<Record<string, unknown>> = [];

  if (isGenericC || dbg.type === 'gdb-host') {
    configurations.push({
      name: `MCU Forge: Debug (${config.name})`,
      type: 'cppdbg',
      request: 'launch',
      program: elfPath,
      args: [],
      stopAtEntry: false,
      cwd: '${workspaceFolder}',
      externalConsole: false,
      MIMode: 'gdb',
      miDebuggerPath: gdbPath,
      preLaunchTask: 'MCU Forge: Build',
      setupCommands: [
        {
          description: 'Enable pretty-printing for gdb',
          text: '-enable-pretty-printing',
          ignoreFailures: true,
        },
      ],
    });
  } else if (dbg.type !== 'none') {
    const baseCortex: Record<string, unknown> = {
      name: `MCU Forge: ${dbg.type.toUpperCase()} Debug (${config.name})`,
      type: 'cortex-debug',
      request: 'launch',
      cwd: '${workspaceFolder}',
      executable: elfPath,
      servertype: dbg.type === 'stlink' ? 'stutil' : dbg.type,
      preLaunchTask: 'MCU Forge: Build',
      runToEntryPoint: 'main',
      showDevDebugOutput: 'raw',
      gdbPath,
    };

    if (config.toolchain.compilerDir.trim()) {
      baseCortex.armToolchainPath = toPosixPath(config.toolchain.compilerDir.trim());
    }
    if (dbg.serverPath.trim()) {
      baseCortex.serverpath = toPosixPath(dbg.serverPath.trim());
    }
    if (dbg.svdFile.trim()) {
      baseCortex.svdFile = dbg.svdFile.startsWith('/') || /^[A-Za-z]:/.test(dbg.svdFile)
        ? toPosixPath(dbg.svdFile)
        : `\${workspaceFolder}/${toPosixPath(dbg.svdFile)}`;
    }
    if (dbg.type === 'openocd') {
      baseCortex.configFiles = [
        dbg.openocdInterface || 'interface/stlink.cfg',
        dbg.openocdTarget || 'target/stm32f1x.cfg',
      ];
      if (dbg.openocdScriptsDir.trim()) {
        baseCortex.searchDir = [toPosixPath(dbg.openocdScriptsDir.trim())];
      }
    } else if (dbg.type === 'jlink') {
      baseCortex.device = dbg.deviceName || 'STM32F103RE';
      baseCortex.interface = dbg.interfaceMode;
    } else if (dbg.type === 'pyocd') {
      baseCortex.targetId = dbg.deviceName || 'cortex_m';
    }

    configurations.push(baseCortex);
  }

  return JSON.stringify({ version: '0.2.0', configurations }, null, 2) + '\n';
}

/** Generate .vscode/settings.json */
export function generateVscodeSettings(config: McuProjectConfig): string {
  const ccPath = resolveCompilerPath(config, 'c');
  const gdbPath = resolveCompilerPath(config, 'gdb');

  const settings: Record<string, unknown> = {
    'clangd.arguments': [
      '--background-index',
      '--compile-commands-dir=${workspaceFolder}',
      `--query-driver=${ccPath}`,
      '--header-insertion=never',
    ],
    'C_Cpp.intelliSenseEngine': 'disabled',
    'files.associations': {
      '*.h': 'c',
      '*.hpp': 'cpp',
      '*.ld': 'plaintext',
    },
  };

  if (config.projectKind !== 'generic-c') {
    settings['cortex-debug.gdbPath'] = gdbPath;
    if (config.toolchain.compilerDir.trim()) {
      settings['cortex-debug.armToolchainPath'] = toPosixPath(config.toolchain.compilerDir.trim());
    }
  }

  return JSON.stringify(settings, null, 2) + '\n';
}

/** Generate .vscode/extensions.json */
export function generateVscodeExtensions(config: McuProjectConfig): string {
  const recs = ['llvm-vs-code-extensions.vscode-clangd'];
  if (config.projectKind !== 'generic-c') {
    recs.push('marus25.cortex-debug');
  } else {
    recs.push('ms-vscode.cpptools');
  }
  if (config.buildSystem === 'cmake') {
    recs.push('ms-vscode.cmake-tools');
  }
  return JSON.stringify({ recommendations: recs }, null, 2) + '\n';
}

/** Generate local.mk for cross-platform teamwork (add local.mk to .gitignore) */
export function generateLocalMk(config: McuProjectConfig): string {
  const lines = [
    `# Machine-specific toolchain paths generated by MCU Forge Studio`,
    `# Add "local.mk" to .gitignore so Windows / macOS / Linux share the same Makefile cleanly.`,
    ``,
    `GCC_PATH := ${withTrailingSlash(config.toolchain.compilerDir)}`,
  ];
  if (config.debugger.type === 'openocd') {
    if (config.debugger.serverPath.trim()) {
      lines.push(`OPENOCD := ${toPosixPath(config.debugger.serverPath.trim())}`);
    }
    if (config.debugger.openocdScriptsDir.trim()) {
      lines.push(`OPENOCD_SCRIPTS := ${toPosixPath(config.debugger.openocdScriptsDir.trim())}`);
    }
  }
  lines.push(``);
  return lines.join('\n');
}

/** Generate flash.jlink command script when debugger.type === 'jlink' */
export function generateFlashJlink(config: McuProjectConfig): string {
  const buildDir = config.buildDir || 'build';
  const flashOrigin = config.memoryLayout?.flashOrigin?.trim() || '0x08000000';
  const loadCmd = config.flags.generateHex
    ? `loadfile ${buildDir}/${config.name}.hex`
    : `loadbin ${buildDir}/${config.name}.bin ${flashOrigin}`;
  return [
    `// Generated by MCU Forge Studio for SEGGER J-Link`,
    `r`,
    `h`,
    loadCmd,
    `r`,
    `g`,
    `q`,
    ``,
  ].join('\n');
}

/** Build a complete preview list of all files that will be generated */
export function buildGeneratedPreviews(config: McuProjectConfig): GeneratedFilePreview[] {
  const files: Array<{ relativePath: string; content: string }> = [];

  if (config.buildSystem === 'makefile') {
    const mkAbs = path.join(config.projectDir, 'Makefile');
    if (!(config.protectExistingBuildFile && fs.existsSync(mkAbs))) {
      files.push({ relativePath: 'Makefile', content: generateMakefile(config) });
    }
    if (config.useLocalMk) {
      files.push({ relativePath: 'local.mk', content: generateLocalMk(config) });
    }
  } else {
    const cmAbs = path.join(config.projectDir, 'CMakeLists.txt');
    if (!(config.protectExistingBuildFile && fs.existsSync(cmAbs))) {
      files.push({ relativePath: 'CMakeLists.txt', content: generateCMakeLists(config) });
    }
    if (config.projectKind !== 'generic-c') {
      files.push({
        relativePath: 'cmake/mcu-toolchain.cmake',
        content: generateCMakeToolchain(config),
      });
    }
  }

  if (config.debugger.type === 'jlink') {
    files.push({ relativePath: 'flash.jlink', content: generateFlashJlink(config) });
  }

  if (config.ide.generateCompileCommands) {
    files.push({
      relativePath: 'compile_commands.json',
      content: generateCompileCommands(config),
    });
  }
  if (config.ide.generateClangd) {
    files.push({ relativePath: '.clangd', content: generateClangdConfig(config) });
  }
  if (config.ide.generateVscodeTasks) {
    files.push({ relativePath: '.vscode/tasks.json', content: generateVscodeTasks(config) });
  }
  if (config.ide.generateVscodeLaunch) {
    files.push({ relativePath: '.vscode/launch.json', content: generateVscodeLaunch(config) });
  }
  if (config.ide.generateVscodeSettings) {
    files.push({ relativePath: '.vscode/settings.json', content: generateVscodeSettings(config) });
  }
  if (config.ide.generateVscodeExtensions) {
    files.push({
      relativePath: '.vscode/extensions.json',
      content: generateVscodeExtensions(config),
    });
  }

  files.push({
    relativePath: MCU_FORGE_CONFIG_FILE,
    content: JSON.stringify(config, null, 2) + '\n',
  });

  return files.map((f) => {
    const abs = path.join(config.projectDir, f.relativePath);
    return {
      relativePath: f.relativePath,
      absolutePath: toPosixPath(abs),
      content: f.content,
      existed: fs.existsSync(abs),
    };
  });
}

/** Write all generated files to disk, optionally creating .bak backups */
export function applyGeneratedFiles(config: McuProjectConfig): {
  written: string[];
  backedUp: string[];
} {
  const previews = buildGeneratedPreviews(config);
  const written: string[] = [];
  const backedUp: string[] = [];

  for (const item of previews) {
    const abs = path.join(config.projectDir, item.relativePath);
    fs.mkdirSync(path.dirname(abs), { recursive: true });

    if (config.ide.backupBeforeOverwrite && fs.existsSync(abs) && item.relativePath !== MCU_FORGE_CONFIG_FILE) {
      const bakPath = `${abs}.bak`;
      if (!fs.existsSync(bakPath)) {
        fs.copyFileSync(abs, bakPath);
        backedUp.push(`${item.relativePath}.bak`);
      }
    }

    fs.writeFileSync(abs, item.content, 'utf8');
    written.push(item.relativePath);
  }

  return { written, backedUp };
}
